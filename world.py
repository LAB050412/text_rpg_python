def get_location(key):
    """지역 키로 지역 데이터를 가져온다."""
    return LOCATIONS.get(key)


def normalize_input(text):
    """
    플레이어가 입력한 문구를 LOCATIONS 의 key 로 변환.
    '에르하임 마을', '마을', '숲' 등 다양한 표현을 허용한다.
    찾지 못하면 None.
    """
    text = text.strip()
    if not text:
        return None
    # 1) 정확히 key 와 일치
    if text in LOCATIONS:
        return text
    # 2) 표시 이름(name) 과 같거나 일부 일치
    for key, data in LOCATIONS.items():
        if text == data["name"] or text in data["name"]:
            return key
    # 3) key 가 입력에 포함 (예: "숲으로" → "고블린 숲")
    for key in LOCATIONS:
        if key in text:
            return key
    return None
